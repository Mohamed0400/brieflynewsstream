export type ConsoleLoginCopy = typeof loginCopy.ar | typeof loginCopy.en;
export type ConsoleDashboardCopy = typeof dashboardCopy.ar | typeof dashboardCopy.en;
export type ConsoleLang = "ar" | "en";

export function withConsoleLang(path: string, lang: ConsoleLang) {
  return lang === "en" ? `${path}?lang=en` : path;
}

export function consoleLoginCopy(lang: string): ConsoleLoginCopy {
  return lang === "en" ? loginCopy.en : loginCopy.ar;
}

export function consoleDashboardCopy(lang: string): ConsoleDashboardCopy {
  return lang === "en" ? dashboardCopy.en : dashboardCopy.ar;
}
