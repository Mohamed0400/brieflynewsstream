export const CONSOLE_LANG_COOKIE = "mna_console_lang";

export function consoleLoginLang(value: string | undefined) {
  return value === "en" ? "en" : "ar";
}

export function persistConsoleLang(lang: "ar" | "en") {
  if (typeof document === "undefined") return;
  document.cookie = `${CONSOLE_LANG_COOKIE}=${lang}; Path=/; Max-Age=31536000; SameSite=Lax`;
}

